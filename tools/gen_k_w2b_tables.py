#!/usr/bin/env python3
"""Generates the Python copy of the stage K wave 2 tables used by K-8g (CVA capital) and K-8i (leverage
ratio, large exposures).

The single source is specifications/tables/stage_k/{mar50_cva,lev_leverage,lex_large_exposures}.json
(ruling KR-50). The Python CLI reads no file for its numbers (as for the Sobol table), so this script
copies the `entries` of each table, unchanged (decimal strings stay strings), into
python/quantforge_core/_k_w2b_tables.py. The check mode compares the values held by that module with
the JSON, so the generated file may be reformatted by ruff without going stale. Standard library only.

    python tools/gen_k_w2b_tables.py           write the Python module
    python tools/gen_k_w2b_tables.py --check   exit 1 if the module differs from the JSON
"""

import ast
import json
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "specifications" / "tables" / "stage_k"
OUT = ROOT / "python" / "quantforge_core" / "_k_w2b_tables.py"
TABLES = {"MAR50": "mar50_cva.json", "LEV": "lev_leverage.json", "LEX": "lex_large_exposures.json"}


def entries(name):
    doc = json.loads((SRC / TABLES[name]).read_text("utf-8"))
    return {e["key"]: e["value"] for e in doc["entries"]}


def render():
    head = (
        '"""GENERATED by tools/gen_k_w2b_tables.py from specifications/tables/stage_k/'
        "mar50_cva.json,\nlev_leverage.json and lex_large_exposures.json (the `entries`, key to value, "
        "decimal strings\nunchanged). Do not edit by hand; `python tools/gen_k_w2b_tables.py --check` "
        'and\ntests/test_stage_k_w2b.py hold this copy equal to the JSON (ruling KR-50)."""\n\n'
        "from typing import Any\n"
    )
    parts = [head]
    for name in TABLES:
        body = pprint.pformat(entries(name), width=96, sort_dicts=False)
        parts.append(f"\n{name}: dict[str, Any] = {body}\n")
    return "".join(parts)


def held():
    tree = ast.parse(OUT.read_text("utf-8"))
    out = {}
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            out[node.target.id] = ast.literal_eval(node.value)
    return out


def main(argv):
    if "--check" in argv:
        have = held() if OUT.exists() else {}
        stale = [n for n in TABLES if have.get(n) != entries(n)]
        if stale:
            print(f"stale: {OUT.relative_to(ROOT)} ({', '.join(stale)}); run python tools/gen_k_w2b_tables.py")
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} equals the three JSON tables")
        return 0
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
