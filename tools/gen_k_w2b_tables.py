#!/usr/bin/env python3
"""Generates the Python and Java copies of the stage K wave 2 tables used by K-8g (CVA capital) and K-8i
(leverage ratio, large exposures).

The single source is specifications/tables/stage_k/{mar50_cva,lev_leverage,lex_large_exposures}.json
(ruling KR-50). The Python CLI reads no file for its numbers (as for the Sobol table), so this script
copies the `entries` of each table, unchanged (decimal strings stay strings), into
python/quantforge_core/_k_w2b_tables.py. The check mode compares the values held by that module with
the JSON, so the generated file may be reformatted by ruff without going stale.

Java has no build-time file mechanism in this repo (wave 1b precedent, tools/gen_k_w1b_tables.py), so
the same entries are also written to java25/src/main/java/org/quantforge/risk/KW2bTables.java: one
read-only tree per table (maps in JSON order, decimal strings unchanged, integers as Long, null kept).
The check mode compares that file's text with what this script would write. Standard library only.

    python tools/gen_k_w2b_tables.py           write the Python module and the Java class
    python tools/gen_k_w2b_tables.py --check   exit 1 if either differs from the JSON
"""

import ast
import json
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "specifications" / "tables" / "stage_k"
OUT = ROOT / "python" / "quantforge_core" / "_k_w2b_tables.py"
JAVA_OUT = ROOT / "java25" / "src" / "main" / "java" / "org" / "quantforge" / "risk" / "KW2bTables.java"
TABLES = {"MAR50": "mar50_cva.json", "LEV": "lev_leverage.json", "LEX": "lex_large_exposures.json"}


def entries(name):
    doc = json.loads((SRC / TABLES[name]).read_text("utf-8"))
    return {e["key"]: e["value"] for e in doc["entries"]}


def render():
    head = (
        '"""GENERATED by tools/gen_k_w2b_tables.py from specifications/tables/stage_k/'
        "mar50_cva.json,\nlev_leverage.json and lex_large_exposures.json (the `entries`, key to value, "
        "decimal strings\nunchanged). Do not edit by hand; `python tools/gen_k_w2b_tables.py --check` "
        'and\ntests/test_stage_k_w2b.py hold this copy equal to the JSON (ruling KR-50)."""\n\n'
        "from typing import Any\n"
    )
    parts = [head]
    for name in TABLES:
        body = pprint.pformat(entries(name), width=96, sort_dicts=False)
        parts.append(f"\n{name}: dict[str, Any] = {body}\n")
    return "".join(parts)


NL = "\n"


def java_value(v, indent):
    """A Java expression for one JSON value, built with the helpers m() and l() of the generated class."""
    pad = " " * (indent + 4)
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return f"{v}L"
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        if all(not isinstance(x, (dict, list)) for x in v):
            return "l(" + ", ".join(java_value(x, indent) for x in v) + ")"
        return "l(" + NL + ("," + NL).join(pad + java_value(x, indent + 4) for x in v) + ")"
    rows = (f"{pad}{json.dumps(k)}, {java_value(x, indent + 4)}" for k, x in v.items())
    return "m(" + NL + ("," + NL).join(rows) + ")"


JAVA_HEAD = """// GENERATED by tools/gen_k_w2b_tables.py from specifications/tables/stage_k/mar50_cva.json,
// lev_leverage.json and lex_large_exposures.json. Do not edit by hand.
package org.quantforge.risk;

import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The entries of the three stage K wave 2b tables (ruling KR-50), key to value: maps in JSON order, decimal strings
 * unchanged, integers as Long, null kept. {@code python tools/gen_k_w2b_tables.py --check} holds this file equal to
 * the JSON, and KW2bTablesTest compares the trees with the files.
 */
final class KW2bTables {
    private KW2bTables() {}

    private static Map<String, Object> m(Object... kv) {
        Map<String, Object> out = new LinkedHashMap<>();
        for (int i = 0; i < kv.length; i += 2) {
            out.put((String) kv[i], kv[i + 1]);
        }
        return Collections.unmodifiableMap(out);
    }

    private static List<Object> l(Object... values) {
        return Collections.unmodifiableList(Arrays.asList(values));
    }
"""


def render_java():
    parts = [JAVA_HEAD]
    for name, src in TABLES.items():
        parts.append(f"{NL}    /** {src}. */{NL}")
        parts.append(f"    static final Map<String, Object> {name} = {java_value(entries(name), 4)};{NL}")
    parts.append("}" + NL)
    return "".join(parts)


def held():
    tree = ast.parse(OUT.read_text("utf-8"))
    out = {}
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            out[node.target.id] = ast.literal_eval(node.value)
    return out


def main(argv):
    if "--check" in argv:
        have = held() if OUT.exists() else {}
        stale = [n for n in TABLES if have.get(n) != entries(n)]
        if stale:
            print(f"stale: {OUT.relative_to(ROOT)} ({', '.join(stale)}); run python tools/gen_k_w2b_tables.py")
            return 1
        java = JAVA_OUT.read_text("utf-8") if JAVA_OUT.exists() else None
        if java != render_java():
            print(f"stale: {JAVA_OUT.relative_to(ROOT).as_posix()}; run python tools/gen_k_w2b_tables.py")
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} and {JAVA_OUT.name} equal the three JSON tables")
        return 0
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    JAVA_OUT.write_text(render_java(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} and {JAVA_OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
