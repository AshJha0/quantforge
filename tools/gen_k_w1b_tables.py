#!/usr/bin/env python3
"""Generates the Java constants classes of the stage K wave 1b shared tables (K-8d SA-CCR, K-8e FRTB IMA backtesting).

The single source is the pair of JSON files under specifications/06-risk/. Rust (`include_str!`) and C++ (`#embed`)
read those files at build time, as the Sobol table does; Java has no such mechanism in this repo, so this script
writes one class per table and a check mode keeps the classes equal to the JSON. Standard library only.

    python tools/gen_k_w1b_tables.py           write the Java files
    python tools/gen_k_w1b_tables.py --check   exit 1 if a generated file is stale
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "specifications" / "06-risk"
OUT = ROOT / "java25" / "src" / "main" / "java" / "org" / "quantforge" / "risk"
HEADER = "// GENERATED by tools/gen_k_w1b_tables.py from specifications/06-risk/{src}. Do not edit by hand.\n"


def num(v):
    """A Java double literal that parses to the same binary64 as the JSON number."""
    return repr(float(v))


def doubles(values):
    return "{" + ", ".join(num(v) for v in values) + "}"


def strings(values):
    return "{" + ", ".join("null" if v is None else json.dumps(v) for v in values) + "}"


def saccr(doc):
    rows = doc["table2"]
    corr = [r["correlation"] for r in rows]
    corr_text = "{" + ", ".join("Double.NaN" if c is None else num(c) for c in corr) + "}"
    mp = doc["mpor_floor_days"]
    ts = doc["treatment_scale"]
    ir = doc["ir_bucket_correlations"]
    bb = doc["ir_bucket_bounds_years"]
    return (
        HEADER.format(src="sa-ccr-parameters.json")
        + f"""package org.quantforge.risk;

/** SA-CCR supervisory parameters (CRE52), generated from sa-ccr-parameters.json. Correlation NaN means none. */
final class SaCcrTables {{
    private SaCcrTables() {{}}

    static final double ALPHA = {num(doc["alpha"])};
    static final double MULTIPLIER_FLOOR = {num(doc["multiplier_floor"])};
    static final int BUSINESS_DAYS_PER_YEAR = {int(doc["business_days_per_year"])};
    static final int MIN_BUSINESS_DAYS = {int(doc["min_business_days"])};
    static final double SUPERVISORY_DURATION_RATE = {num(doc["supervisory_duration_rate"])};
    static final double IR_RHO_B1_B2 = {num(ir["b1_b2"])};
    static final double IR_RHO_B2_B3 = {num(ir["b2_b3"])};
    static final double IR_RHO_B1_B3 = {num(ir["b1_b3"])};
    static final double IR_BUCKET1_BELOW = {num(bb["bucket1_below"])};
    static final double IR_BUCKET2_UP_TO = {num(bb["bucket2_up_to_and_including"])};
    static final double MARGINED_MF_SCALE = {num(doc["margined_maturity_factor_scale"])};
    static final int MPOR_DAILY = {int(mp["daily_margin"])};
    static final int MPOR_NON_DAILY_BASE = {int(mp["non_daily_base"])};
    static final int MPOR_LARGE_OR_ILLIQUID = {int(mp["large_or_illiquid"])};
    static final int MPOR_LARGE_TRADES_ABOVE = {int(mp["large_netting_set_trades_above"])};
    static final int MPOR_DISPUTE_MULTIPLIER = {int(mp["dispute_multiplier"])};
    static final double SCALE_NORMAL = {num(ts["NORMAL"])};
    static final double SCALE_BASIS = {num(ts["BASIS"])};
    static final double SCALE_VOLATILITY = {num(ts["VOLATILITY"])};
    static final double CDO_NUMERATOR = {num(doc["cdo_delta"]["numerator"])};
    static final double CDO_SLOPE = {num(doc["cdo_delta"]["slope"])};

    /** CRE52.72 Table 2, one entry per row. */
    static final String[] CLASS = {strings([r["asset_class"] for r in rows])};
    static final String[] SUBCLASS = {strings([r["subclass"] or "" for r in rows])};
    static final double[] FACTOR = {doubles([r["supervisory_factor"] for r in rows])};
    static final double[] CORRELATION = {corr_text};
    static final double[] OPTION_VOLATILITY = {doubles([r["option_volatility"] for r in rows])};
    static final String[] HEDGING_SET = {strings([r.get("hedging_set") for r in rows])};
}}
"""
    )


def frtb(doc):
    return (
        HEADER.format(src="frtb-ima-backtest-tables.json")
        + f"""package org.quantforge.risk;

/** FRTB IMA backtesting tables (MAR32, MAR99), generated from frtb-ima-backtest-tables.json. */
final class FrtbBacktestTables {{
    private FrtbBacktestTables() {{}}

    static final double COVERAGE = {num(doc["coverage"])};
    static final double AMBER_FROM = {num(doc["amber_from_cumulative"])};
    static final double RED_FROM = {num(doc["red_from_cumulative"])};
    static final long TABLE_OBSERVATIONS = {int(doc["table_observations"])};
    static final double[] MULTIPLIER_250 = {doubles(doc["multiplier_250"])};
    static final double MULTIPLIER_RED = {num(doc["multiplier_red"])};
    static final long DESK_LIMIT_99 = {int(doc["desk_limit_99"])};
    static final long DESK_LIMIT_975 = {int(doc["desk_limit_975"])};
    static final long MAX_OBSERVATIONS = {int(doc["max_observations"])};
}}
"""
    )


def outputs():
    s = json.loads((SPEC / "sa-ccr-parameters.json").read_text(encoding="utf-8"))
    f = json.loads((SPEC / "frtb-ima-backtest-tables.json").read_text(encoding="utf-8"))
    return {OUT / "SaCcrTables.java": saccr(s), OUT / "FrtbBacktestTables.java": frtb(f)}


def main(argv):
    check = "--check" in argv
    stale = []
    for path, text in outputs().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("stale (run python tools/gen_k_w1b_tables.py):", ", ".join(stale))
        return 1
    print(("checked " if check else "wrote ") + str(len(outputs())) + " files" + (f", updated {stale}" if stale and not check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
