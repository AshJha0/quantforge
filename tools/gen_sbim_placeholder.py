#!/usr/bin/env python3
"""Writes specifications/tables/stage_k/sbim-placeholder.json: the PLACEHOLDER weights, correlations and thresholds
of item K-8h, the project's own sensitivity-based initial margin on placeholder weights ("sbim"; spec
specifications/06-risk/sbim-placeholder.md, rulings KR-130 onward).

Every number below is an artificial round number generated by a stated rule. None is taken from, fitted to, or
compared with any industry or regulatory margin model's parameter set or any licensed calibration, and no such
document or file was opened to write this (owner decision 2026-11-19: the project uses no ISDA material). The rules
are deliberately artificial so that nobody can mistake the table for a calibration:

  tenors           1W, 1Y, 5Y, 10Y with index k = 1..4 and days 7, 365, 1825, 3650
  IR delta RW      10 x k                                   (10, 20, 30, 40)
  IR rho(k, l)     1 - 0.1 |k - l|  between tenors           (0.9, 0.8, 0.7)
  IR gamma         0.25 between any two currencies
  EQ delta RW      10 x b for buckets b = 1..3, 40 for RESIDUAL
  EQ rho           0.5 within a numbered bucket, 0.25 within RESIDUAL; gamma 0.25 between numbered buckets
  FX delta RW      5 for every currency; rho 0.5 between any two currencies
  vega RW          IR 2, EQ 3 (one weight per risk class); vega correlations equal the delta correlations
  thresholds       delta: IR 100, EQ 100, FX 1000; vega: IR 1000, EQ 1000 (amount units of the input)
  curvature        SF(t) = 0.25 min(1, 20 / t), t in days; z = 2 (lambda = (z^2 - 1)(1 + theta) - theta);
                   correlations squared
  rho_class        0.2 between any two of IR, FX, EQ within a group

It also writes specifications/tables/stage_k/sbim-ir-delta-g.json, the table of the stage G operation
`xva.sbim.ir_delta` (formerly `xva.simm.ir_delta`; rulings KR-150 to KR-155), by the same rule on the stage G
tenor grid. That operation takes weights and correlations as inputs (G-43); the table is what the goldens, the
tutorial and the docs feed it. It replaced hand-typed values whose origin was not documented (stage K round 1, on main since 2026-11-20):

  tenors           0.25, 1, 2, 5, 10, 30 years with index k = 1..6 (labels only; no number depends on them)
  RW               10 x k                                   (10, 20, 30, 40, 50, 60)
  rho(k, l)        1 - 0.1 |k - l|                          (0.9, 0.8, 0.7, 0.6, 0.5)

    python tools/gen_sbim_placeholder.py           write both tables
    python tools/gen_sbim_placeholder.py --check   exit 1 if a committed table differs from the generator output
Standard library only. Numbers are written as decimal strings (HR-12).
"""

import json
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "specifications" / "tables" / "stage_k" / "sbim-placeholder.json"
OUT_G = ROOT / "specifications" / "tables" / "stage_k" / "sbim-ir-delta-g.json"

NOTICE = ("PLACEHOLDER WEIGHTS. Artificial round numbers generated by the rules in this file for QuantForge's own "
          "sensitivity-based initial margin aggregation (a project definition). They have no relation to any industry "
          "or regulatory margin model's parameters, any licensed calibration or any vendor file, none of which was "
          "opened to write them. Results computed with them are not a regulatory or industry-standard initial margin "
          "and must not be used for margin calls.")


def dec(x):
    """Exact decimal string of a Fraction with a terminating decimal expansion (no binary rounding)."""
    x = Fraction(x)
    if x.denominator == 1:
        return str(x.numerator)
    sign = "-" if x < 0 else ""
    x = abs(x)
    whole, rem = divmod(x.numerator, x.denominator)
    digits = []
    for _ in range(30):
        if rem == 0:
            break
        rem *= 10
        d, rem = divmod(rem, x.denominator)
        digits.append(str(d))
    if rem != 0:
        raise ValueError(f"{x} has no short decimal form")
    return f"{sign}{whole}." + "".join(digits)


TENORS = [("1W", 7), ("1Y", 365), ("5Y", 1825), ("10Y", 3650)]
EQ_BUCKETS = ["1", "2", "3"]


def build():
    labels = [t for t, _ in TENORS]
    ir_rho = [[dec(1 if k == l else 1 - Fraction(1, 10) * abs(k - l)) for l in range(1, 5)] for k in range(1, 5)]
    eq_rw = {b: dec(10 * int(b)) for b in EQ_BUCKETS}
    eq_rw["RESIDUAL"] = dec(40)
    return {
        "name": "sbim-placeholder",
        "placeholder": True,
        "label": "placeholder weights",
        "notice": NOTICE,
        "status": "PROPOSED (stage K item K-8h, spec lane 2026-11-19)",
        "generator": "tools/gen_sbim_placeholder.py (the file must equal its output: tools/test_sbim_placeholder.py)",
        "numbers": "decimal strings (HR-12)",
        "rules": [
            "tenors 1W, 1Y, 5Y, 10Y: index k = 1..4, days 7, 365, 1825, 3650",
            "IR delta RW = 10 x k; IR rho(k, l) = 1 - 0.1 |k - l|; IR gamma 0.25 between any two currencies",
            "EQ delta RW = 10 x b for buckets 1..3, 40 for RESIDUAL; EQ rho 0.5 within a numbered bucket, "
            "0.25 within RESIDUAL; EQ gamma 0.25 between numbered buckets",
            "FX delta RW 5; FX rho 0.5 between any two currencies",
            "vega RW: IR 2, EQ 3; vega correlations equal the delta correlations",
            "concentration thresholds: delta IR 100, EQ 100, FX 1000; vega IR 1000, EQ 1000",
            "curvature: SF(t) = 0.25 min(1, 20 / t), t in days; z = 2; correlations squared",
            "rho_class 0.2 between any two of IR, FX, EQ within a group",
        ],
        "tenors": [{"label": t, "index": i + 1, "days": d} for i, (t, d) in enumerate(TENORS)],
        "IR": {
            "delta": {"rw": {t: dec(10 * (i + 1)) for i, t in enumerate(labels)},
                      "rho": {"order": labels, "matrix": ir_rho},
                      "gamma": dec(Fraction(1, 4)),
                      "threshold": dec(100)},
            "vega": {"rw": dec(2), "threshold": dec(1000),
                     "rho": "as delta", "gamma": "as delta"},
        },
        "FX": {
            "delta": {"rw": dec(5), "rho": dec(Fraction(1, 2)), "threshold": dec(1000)},
        },
        "EQ": {
            "delta": {"rw": eq_rw,
                      "rho": {b: dec(Fraction(1, 2)) for b in EQ_BUCKETS} | {"RESIDUAL": dec(Fraction(1, 4))},
                      "gamma": dec(Fraction(1, 4)),
                      "threshold": dec(100)},
            "vega": {"rw": dec(3), "threshold": dec(1000),
                     "rho": "as delta", "gamma": "as delta"},
        },
        "curvature": {"sf_scale": dec(Fraction(1, 4)), "sf_days": dec(20), "z": dec(2),
                      "correlations": "squares of the vega correlations (rho^2 within a bucket, gamma^2 across)"},
        "rho_class": {"pairs": [["IR", "FX"], ["IR", "EQ"], ["FX", "EQ"]], "value": dec(Fraction(1, 5))},
    }


G_TENORS = ["0.25", "1", "2", "5", "10", "30"]


def build_g():
    """Stage G table (KR-150): RW = 10 x k and rho(k, l) = 1 - 0.1 |k - l| on the six stage G tenors."""
    n = len(G_TENORS)
    return {
        "name": "sbim-ir-delta-g",
        "placeholder": True,
        "label": "placeholder weights",
        "notice": NOTICE,
        "status": "ruled 2026-11-19 (KR-150, KR-151; stage K margin lane); replaces hand-typed values of v0.7.0 to v0.10.0",
        "generator": "tools/gen_sbim_placeholder.py (the file must equal its output: tools/test_sbim_placeholder.py)",
        "operation": "xva.sbim.ir_delta (deprecated alias xva.simm.ir_delta until v1.0.0)",
        "numbers": "decimal strings (HR-12)",
        "rules": [
            "tenors 0.25, 1, 2, 5, 10, 30 years: index k = 1..6 (labels only; no number depends on them)",
            "RW = 10 x k",
            "rho(k, l) = 1 - 0.1 |k - l|",
        ],
        "tenors_years": G_TENORS,
        "risk_weights": [dec(10 * k) for k in range(1, n + 1)],
        "correlations": [[dec(1 - Fraction(abs(k - l), 10)) for l in range(n)] for k in range(n)],
    }


def text():
    return json.dumps(build(), indent=1, ensure_ascii=True) + "\n"


def text_g():
    return json.dumps(build_g(), indent=1, ensure_ascii=True) + "\n"


def main():
    outputs = ((OUT, text()), (OUT_G, text_g()))
    if "--check" in sys.argv[1:]:
        bad = [p for p, t in outputs if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in bad:
            print(f"{p} differs from the generator output; regenerate with tools/gen_sbim_placeholder.py")
        if bad:
            return 1
        print("sbim-placeholder.json and sbim-ir-delta-g.json equal the generator output")
        return 0
    for p, t in outputs:
        p.write_text(t, encoding="utf-8", newline="\n")
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
