#!/usr/bin/env python3
"""Writes docs/results.md, the public results page (plan 14.8 K-7, check RE6, ruling KR-224, confirmed 2026-11-20).

    python tools/results_page.py              write the page
    python tools/results_page.py --check      exit 1 if the page is stale or a verdict row is not backed
    python tools/results_page.py --self-test  planted faults must fail

Plain idea: one page that says, per stage, what was tested and what came out, misses first, with every figure
either counted from the tree when the page is built or quoted word for word from the file that holds it. No number
on the page is typed into this script.

Sources (standard library only):
- recorded misses, moves to a later release and release gaps: the register table in docs/known-issues.md
  ("Recorded misses, ..."), itself checked by tools/check_known_issues.py;
- golden cases by class per suite directory: tools/case_figures.counts();
- outside-checked shares per stage and per plan item: oracle/OUTSIDE_SHARES.json (tools/outside_shares.py);
- the release state: tools/site_facts.json;
- stage names and tags: the first table of ROADMAP.md;
- mutation results, studies and benchmark verdicts: tools/results_verdicts.json, each row with an evidence path
  that must exist and a quote that must occur verbatim in it.
"""
import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
PAGE = ROOT / "docs" / "results.md"
VERDICTS = ROOT / "tools" / "results_verdicts.json"
DIR_STAGE = {"core": "A", "stage_b": "B", "stage_c": "C", "r2": "R2", "stage_d": "D", "stage_e": "E", "stage_e_b": "E",
             "stage_f": "F", "r6": "R6", "stage_g": "G", "stage_g_e1": "G", "stage_i": "I", "stage_j": "J",
             "stage_h": "H", "stage_k": "K"}
ORDER = ["A", "B", "C", "D", "R2", "E", "F", "G", "I", "R6", "J", "H", "K"]


def verdict_problems(doc, root=ROOT):
    out = []
    for i, r in enumerate(doc["rows"]):
        ev = r.get("evidence", "")
        if not ev:
            out.append(f"row {i + 1}: no evidence path")
            continue
        p = Path(root) / ev
        if not p.is_file():
            out.append(f"row {i + 1}: evidence {ev} does not exist")
            continue
        if not r.get("quote") or r["quote"] not in p.read_text(encoding="utf-8"):
            out.append(f"row {i + 1}: the quote is not in {ev}")
    return out


def register_rows(text):
    m = re.search(r"^## Recorded misses[^\n]*\n(.*?)(?=^## )", text, re.M | re.S)
    if not m:
        return []
    rows = []
    for line in m.group(1).splitlines():
        if line.startswith("| ") and not line.startswith("| Id ") and not line.startswith("|---"):
            rows.append([c.strip() for c in line.strip().strip("|").split(" | ")])
    return rows


def roadmap_stages(text):
    out = {}
    for line in text.splitlines():
        m = re.match(r"^\| ([A-K]) ([^|]+) \| \d+ \| ([^|]+) \| (v[\d.]+) \|$", line)
        if m:
            out[m.group(1)] = (m.group(2).strip(), m.group(3).strip(), m.group(4))
    return out


def pct(x):
    return f"{100 * x:.1f}%"


def render(root=ROOT):
    import case_figures
    root = Path(root)
    facts = json.loads((root / "tools" / "site_facts.json").read_text(encoding="utf-8"))
    shares = json.loads((root / "oracle" / "OUTSIDE_SHARES.json").read_text(encoding="utf-8"))
    verdicts = json.loads((root / "tools" / "results_verdicts.json").read_text(encoding="utf-8"))
    stages = roadmap_stages((root / "ROADMAP.md").read_text(encoding="utf-8"))
    reg = register_rows((root / "docs" / "known-issues.md").read_text(encoding="utf-8"))
    per = case_figures.counts(root)
    by_stage = {}
    for d, c in per.items():
        st = DIR_STAGE.get(d, d)
        by_stage.setdefault(st, {"ok": 0, "error": 0, "inv": 0})
        by_stage[st]["ok"] += c["ok"]
        by_stage[st]["error"] += c["error"]
        by_stage[st]["inv"] += c["same_as"] + c["any"]
    fig = case_figures.figures(root)
    L = ["# Results", "",
         "Generated by `tools/results_page.py` from the files it names; do not edit. `repo-gates` runs `--check`, which "
         "also fails if a verdict row's quote is not in its evidence file (plan 14.8 K-7, ruling KR-224, confirmed 2026-11-20).", "",
         "**Plain idea.** What was tested, stage by stage, and what came out, with the misses first. Every figure is "
         "counted from the repository when this page is built or quoted word for word from the file named beside it. "
         "Validation is self-assessment: there is no second review (owner decision 2026-11-18). Status rung of every "
         "built stage: Implemented; nothing is Validated, Benchmarked or Operationally tested "
         "([status ladder](validation/status-ladder.md)).", "",
         f"**Release state (from `tools/site_facts.json`).** Latest release {facts['release']}, released {facts['released']}. "
         f"On main: {facts['main_state']}.", "",
         "## Recorded misses, moves to a later release and release gaps", "",
         "Read from the register table in [known issues](known-issues.md); a miss stays a miss and no threshold was moved.", "",
         "| Id | Kind | What | Source | Status |", "|---|---|---|---|---|"]
    L += [f"| {' | '.join(r[:5])} |" for r in reg if len(r) >= 5]
    if not reg:
        L.append("| none found | | | | |")
    L += ["", "## Golden cases and outside checks per stage", "",
          f"All suites: {fig['value_checked']} value-checked, {fig['error_cases']} error and {fig['invariance_cases']} "
          f"invariance cases ({fig['total_cases']} in all; [case figures](case-figures.md)). A value-checked case must "
          "return the oracle's numbers within a stated tolerance; an error case checks the error code only; an "
          "invariance case checks that two related inputs get the same answer.", "",
          "Outside-checked share: value-checked cases re-derived outside the author's own code, by an outside library or, "
          "where the rule allows it, by a blind re-derivation by a second AI lane that saw the rules and inputs but not the "
          "answers; never by a person (README, \"Words used here\"). One definition on every page: "
          "`tools/case_figures.py outside_pair()` (rule R6-13, decision D6; floor "
          f"{pct(shares['floor'])} per stage, and from "
          "stage H on per plan item). Stages A to C, R2 and R6 are outside the share table. The share's denominator is the "
          "share table's own count (without generated sweeps), so it can be smaller than the value-checked column. The tag "
          "column is the plan's tag from ROADMAP: stage K is not tagged yet (target v1.0.0).", "",
          "| Stage | Name | Planned tag | Demo (ROADMAP) | Value-checked | Error | Invariance | Outside-checked value cases | Floor |",
          "|---|---|---|---|---:|---:|---:|---|---|"]
    for st in ORDER + sorted(set(by_stage) - set(ORDER)):
        if st not in by_stage:
            continue
        name, demo, tag = stages.get(st, ("", "", ""))
        c = by_stage[st]
        s = shares["stages"].get(st)
        if s:
            counted, cases, share = case_figures.outside_pair(s)  # the one definition, shared with README and case-figures
            oc = f"{counted} of {cases} ({pct(share)})"
            fl = "met" if s.get("meets_floor") else "NOT MET"
        else:
            oc, fl = "not in the share table", ""
        L.append(f"| {st} | {name} | {tag} | {demo} | {c['ok']:,} | {c['error']:,} | {c['inv']:,} | {oc} | {fl} |")
    for st in ("H", "K"):
        items = shares["stages"].get(st, {}).get("per_item")
        if not items:
            continue
        L += ["", f"Stage {st} per plan item:", "", "| Item | Value cases | Outside-checked | Share | Per item |", "|---|---:|---:|---:|---|"]
        for it, v in sorted(items.items()):
            L.append(f"| {it} | {v['cases']} | {v['counted_with_rederivation']} | {pct(v['share_with_rederivation'])} | "
                     f"{'met' if v.get('meets_item_floor') else 'NOT MET'} |")
    cov_files = sorted((root / "benchmarks" / "results" / "coverage").glob("coverage-ci-*.json"))
    if cov_files:
        cov = json.loads(cov_files[-1].read_text(encoding="utf-8"))
        rel = cov_files[-1].relative_to(root).as_posix()
        floors = {}
        L += ["", "## Unit-test line coverage", "",
              f"Measured in CI by `{cov['workflow']}` (run [{cov['run']}]({cov['run_url']}), {cov['event']}, head "
              f"`{cov['head_sha'][:8]}`, {cov['date']}; {cov['tools']}), copied verbatim from the run log into `{rel}`. "
              "Line coverage of each language's library by its own unit tests. The gate fails a language below its floor "
              "(`conformance/quality/floors.json`) or any file below 90% outside the allow-list "
              "(`conformance/quality/coverage_allow.json`). Line coverage says which lines ran, not that their results "
              "were checked; the golden cases and mutation testing are the checks on results.", "",
              "| Language | Lines covered | Lines | Line coverage | Floor | Files below 90% |", "|---|---:|---:|---:|---:|---:|"]
        below = {}
        for line in cov["log_lines"]:
            m = re.match(r"(\w+): library (\d+)/(\d+) lines, [\d.]+% against the floor (\d+)%", line)
            if m:
                floors[m.group(1)] = (int(m.group(2)), int(m.group(3)), m.group(4))
            m = re.match(r"(\w+): per-file gate at 90%: (\d+) file", line)
            if m:
                below[m.group(1)] = m.group(2)
        for lang, (c, n, fl) in sorted(floors.items()):
            L.append(f"| {lang} | {c:,} | {n:,} | {100 * c / n:.1f}% | {fl}% | {below.get(lang, 'not recorded')} |")
    for sec in ("Mutation testing", "Studies and gates", "Benchmarks"):
        rows = [r for r in verdicts["rows"] if r["section"] == sec]
        if not rows:
            continue
        L += ["", f"## {sec}", ""]
        if sec == "Mutation testing":
            L += ["Gate (`conformance/mutation/stages.json`, `.github/workflows/mutation-stage.yml`): at least 80% of a "
                  "40-mutant sample killed per module and language, with a 95% Wilson lower bound of at least 65%. Scores "
                  "are sampled: on pull requests 40 mutants per module and language, not every mutant, so a score of 32 of "
                  "40 (80%) has a Wilson 95% interval of about 65% to 90%. Which surviving mutants are equivalent (cannot "
                  "change any output) is the project's own judgement, written by the lanes that wrote the code, with no "
                  "second review; unsigned Equivalent rows stay counted as survivors, so scores are lower bounds. Per-run "
                  "scores are not stored in the tree; the rows below quote the files that recorded them.", ""]
        L += ["| Stage | Verdict | Quoted from the evidence | Evidence |", "|---|---|---|---|"]
        for r in rows:
            q = r["quote"].replace("|", "\\|")
            L.append(f"| {r['stage']} | {r['verdict']} | \"{q}\" | `{r['evidence']}` |")
    L += ["", "## What this page does not show", "",
          "- Tradable profitability: the project uses free public data only and makes no performance claim (README, "
          "\"What it can and cannot show\").",
          "- That the checks are sufficient: a count says what is checked, not that nothing is missing.",
          "- Per-model detail: see the [model validation reports](validation/models/README.md).", ""]
    return "\n".join(L)


def problems(root=ROOT):
    root = Path(root)
    out = verdict_problems(json.loads((root / "tools" / "results_verdicts.json").read_text(encoding="utf-8")), root)
    page = root / "docs" / "results.md"
    if not page.is_file() or page.read_text(encoding="utf-8") != render(root):
        out.append("docs/results.md is stale: run python tools/results_page.py")
    return out


def self_test():
    failures = []
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        (t / "ev.md").write_text("Rust 93.4% killed\n", encoding="utf-8")
        good = {"rows": [{"quote": "Rust 93.4%", "evidence": "ev.md"}]}
        planted = {"a verdict with no evidence path": {"rows": [{"quote": "x", "evidence": ""}]},
                   "an evidence file that does not exist": {"rows": [{"quote": "x", "evidence": "missing.md"}]},
                   "a quote not in its evidence (a typed number)": {"rows": [{"quote": "Rust 95.0%", "evidence": "ev.md"}]}}
        if verdict_problems(good, t):
            failures.append(f"good row reported: {verdict_problems(good, t)}")
        failures += [f"planted fault not caught: {k}" for k, v in planted.items() if not verdict_problems(v, t)]
    if failures:
        print("self-test FAILED:\n" + "\n".join(failures), file=sys.stderr)
        return 1
    print(f"self-test: a backed verdict passes and {len(planted)} planted faults fail")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if a.check:
        found = problems()
        for p in found:
            print(f"results page: {p}", file=sys.stderr)
        if not found:
            print("results page: current, every verdict backed by its evidence file")
        return 1 if found else 0
    bad = verdict_problems(json.loads(VERDICTS.read_text(encoding="utf-8")))
    if bad:
        for p in bad:
            print(f"results page: {p}", file=sys.stderr)
        return 1
    PAGE.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {PAGE.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
