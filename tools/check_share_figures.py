#!/usr/bin/env python3
"""Stage K outside-share figures in the docs agree with the generated JSON (audit KF-3, KF-13). Standard library only.

Plain idea: `oracle/OUTSIDE_SHARES.json` is generated by `tools/outside_shares.py`; prose that quotes an
"N of M" share for a stage K item is hand-written and goes stale when a count changes (KF-13 found eleven
such places). This check reads every tracked Markdown file outside `program/` (earlier lanes' records are
history) and, for each "share" or "Challenger" followed in the same sentence by "N of M", finds the stage K
items the line names (suite names such as `saccr_k`, labels such as K-8d, or the item a spec page or
tutorial is about). The figure must equal one of those items' "counted with re-derivation of cases" pairs
or the stage K total. Lines naming no stage K item are not checked.

    python tools/check_share_figures.py [--root DIR] [--self-test]

Exit 0: every checked figure agrees. Exit 1: a list of file:line, the figure found, the figures allowed.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The page a file is about, when its share lines do not repeat the suite name.
FILE_ITEM = {
    "specifications/06-risk/sa-ccr.md": "K-8d",
    "specifications/06-risk/frtb-ima-backtest.md": "K-8e",
    "docs/getting-started/tutorial-56-sa-ccr-example-1.md": "K-8d",
}
# Files another lane is rewriting at the time this gate was added (k-r2, 2026-11-20). Each entry is a
# known stale figure, listed in the k-r2-kf2 report; remove the entry when that lane merges.
PENDING: set[str] = set()
SHARE = re.compile(r"\b(?:share|Challenger)\b([^.\n]|\.(?=[A-Za-z0-9_]))*?\b(\d+) of (\d+)\b")
LABEL = re.compile(r"\bK-(4a|4b|4c|5a|8d|8e)\b")


def load(root):
    k = json.loads((root / "oracle/OUTSIDE_SHARES.json").read_text(encoding="utf-8"))["stages"]["K"]
    items, suites = {}, {}
    for item, v in k["per_item"].items():
        pair = (v["counted_with_rederivation"], v["cases"])
        items[item] = pair
        for s in v["suites"]:
            suites[s] = pair
    w = k["without_sweeps"]
    return items, suites, (w["counted_with_rederivation"], w["cases"])


def check_text(rel, text, items, suites, total):
    bad = []
    for n, line in enumerate(text.split("\n"), 1):
        for m in SHARE.finditer(line):
            # items named in the bullet head (first 160 characters) or from 300 characters before the figure to 80 after it, so a long line mixing stages is read locally
            win = line[:160] + " " + line[max(0, m.start() - 300):m.end() + 80]
            allowed = set()
            for s, pair in suites.items():
                if re.search(rf"\b{re.escape(s)}\b", win):
                    allowed.add(pair)
            for lm in LABEL.finditer(win):
                allowed.add(items["K-" + lm.group(1)])
            if rel in FILE_ITEM:
                allowed.add(items[FILE_ITEM[rel]])
            if not allowed:
                continue
            allowed.add(total)
            got = (int(m.group(2)), int(m.group(3)))
            if got not in allowed:
                bad.append(f"{rel}:{n}: share {got[0]} of {got[1]}; allowed "
                           + ", ".join(f"{a} of {b}" for a, b in sorted(allowed)))
    return bad


def tracked(root):
    out = subprocess.run(["git", "ls-files", "*.md"], cwd=root, capture_output=True, text=True, check=True).stdout
    return [p for p in out.split("\n") if p and not p.startswith("program/") and p not in PENDING
            and not p.startswith("oracle/OUTSIDE_SHARES")]


def self_test(root):
    items, suites, total = load(root)
    a, b = items["K-8d"]
    good = f"Outside share {a} of {b} for `saccr_k`."
    stale = f"Outside share {a} of {b - 3}; four leaked cases excluded (K-8d)."
    assert not check_text("x.md", good, items, suites, total)
    assert check_text("x.md", stale, items, suites, total), "planted stale figure not caught"
    assert check_text("specifications/06-risk/sa-ccr.md", f"Outside share: {a} of {b - 3} value cases", items, suites, total)
    assert not check_text("y.md", "blind re-derivation 11 of 11 MATCH, `saccr_k`", items, suites, total)
    print("check_share_figures self-test: planted stale figures caught, correct figures pass")


def main(argv):
    root = ROOT
    if "--root" in argv:
        root = Path(argv[argv.index("--root") + 1]).resolve()
    if "--self-test" in argv:
        self_test(root)
        return 0
    items, suites, total = load(root)
    bad = []
    for rel in tracked(root):
        bad += check_text(rel, (root / rel).read_text(encoding="utf-8", errors="replace"), items, suites, total)
    if bad:
        print("stage K share figures differ from oracle/OUTSIDE_SHARES.json:")
        print("\n".join("  " + b for b in bad))
        return 1
    print("stage K share figures agree with oracle/OUTSIDE_SHARES.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
