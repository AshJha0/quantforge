#!/usr/bin/env python3
"""Stage K outside-share figures in the docs agree with the generated JSON (audits KF-3, KF-13, KF-18). Standard library only.

Plain idea: `oracle/OUTSIDE_SHARES.json` is generated by `tools/outside_shares.py`. The main defence is that the
docs quote the stage K total and the per-item list from generated blocks, which `outside_shares.py --check`
compares byte for byte. This gate is the second line, for prose written by hand outside those blocks. It reads
every tracked Markdown file outside `program/` (earlier lanes' records are history) and checks, on each line:

  1. every "<item> N of M" (an item name right before the figure: a stage K suite such as `saccr_k`, a label such
     as K-8d or "K-8 guard", or "SA-CCR", "FRTB backtesting") and every "N of M ... for <item>" equals that item's
     "counted with re-derivation of cases" pair, and a percentage right after it, "(P%", equals its share;
  2. "stage K ... share ... N of M" and "K P% (N of M" equal the stage K total, with its percentage;
  3. on a line that mentions an outside share, an unpaired "share ... N of M" equals one of the items the line
     names (or the item a spec page or tutorial is about) or the stage total (the KF-3 rule);
  4. "every item meets" or "every item at least 60%" said of stage K (the nearest stage marker before it is a
     stage K one) fails while any stage K item is under the per-item floor.

    python tools/check_share_figures.py [--root DIR] [--self-test]

Exit 0: every checked figure agrees. Exit 1: a list of file:line and what disagrees.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The page a file is about, when its share lines do not repeat the suite name.
FILE_ITEM = {
    "specifications/06-risk/sa-ccr.md": "K-8d",
    "specifications/06-risk/frtb-ima-backtest.md": "K-8e",
    "docs/getting-started/tutorial-56-sa-ccr-example-1.md": "K-8d",
}
PENDING: set[str] = set()
SHARE_LINE = re.compile(r"\b(?:share|Challenger|outside-check)\b|\b60%", re.I)
SHARE = re.compile(r"\b(?:share|Challenger)\b([^.\n]|\.(?=[A-Za-z0-9_]))*?\b(\d+) of (\d+)\b")
LABEL = re.compile(r"\bK-(4a|4b|4c|5a|8d|8e)\b")
# Names that may stand right before a figure, beyond the suite names and the K labels.
ALIASES = {"K-8 guard": "K-8 guard", "K-8 method": "K-8", "SA-CCR": "K-8d", "FRTB backtesting": "K-8e",
           "K-8d SA-CCR": "K-8d", "K-8e FRTB backtesting": "K-8e"}
FIG = r"(\d+) of (\d+)(?: value cases)?(?: \((\d+(?:\.\d+)?)%)?"
TOTAL = [re.compile(r"\b[Ss]tage K\b[^.|\n]{0,60}?\bshare\b[^.|\n\d]{0,30}" + FIG),
         re.compile(r"\bK (\d+\.\d)% \((\d+) of (\d+)\b")]
EVERY = re.compile(r"\b[Ee]very (?:stage K )?(?:round 1 )?item (?:meets|at least 60%)")
H_MARK = re.compile(r"\b(?:[Ss]tage H|H \d+\.\d%|H-\d+[a-z]?)\b")


def load(root):
    k = json.loads((root / "oracle/OUTSIDE_SHARES.json").read_text(encoding="utf-8"))["stages"]["K"]
    items, suites, met = {}, {}, True
    for item, v in k["per_item"].items():
        pair = (v["counted_with_rederivation"], v["cases"])
        items[item] = pair
        met = met and v["meets_item_floor"]
        for s in v["suites"]:
            suites[s] = item
    w = k["without_sweeps"]
    return {"items": items, "suites": suites, "total": (w["counted_with_rederivation"], w["cases"]), "all_met": met}


def names(d):
    n = {f"`{s}`": it for s, it in d["suites"].items()}
    n.update({s: it for s, it in d["suites"].items()})
    n.update({f"K-{x}": f"K-{x}" for x in ("4a", "4b", "4c", "5a", "8d", "8e") if f"K-{x}" in d["items"]})
    n.update({a: it for a, it in ALIASES.items() if it in d["items"]})
    return n


def pct(a, b):
    return f"{100 * a / b:.1f}"


def check_text(rel, text, d):
    bad = []
    nm = names(d)
    alt = "|".join(re.escape(x) for x in sorted(nm, key=len, reverse=True))
    before = re.compile(rf"(?<![\w-])({alt})(?![\w-])[\s:]*(?:share[\s:]*)?" + FIG)
    after = re.compile(FIG + rf"\s+for\s+({alt})(?![\w-])")
    stage_marks = re.compile(rf"(?<![\w-])(?:{alt})(?![\w-])|\b[Ss]tage K\b|\bK \d+\.\d%|\bround 1 item")
    for n, line in enumerate(text.split("\n"), 1):
        where = f"{rel}:{n}"
        share_line = bool(SHARE_LINE.search(line))
        paired = set()

        def judge(item, a, b, p, span):
            paired.add(span)
            want = d["items"][item]
            if (a, b) != want:
                bad.append(f"{where}: {item} {a} of {b}; generated {want[0]} of {want[1]}")
            elif p is not None and p != pct(*want) and p != pct(*want).rstrip("0").rstrip("."):
                bad.append(f"{where}: {item} {a} of {b} ({p}%); generated {pct(*want)}%")

        if share_line:
            for m in before.finditer(line):
                judge(nm[m.group(1)], int(m.group(2)), int(m.group(3)), m.group(4), m.span(2))
            for m in after.finditer(line):
                judge(nm[m.group(4)], int(m.group(1)), int(m.group(2)), m.group(3), m.span(1))
        for i, rx in enumerate(TOTAL):
            for m in rx.finditer(line):
                g = m.groups()
                a, b, p = (g[0], g[1], g[2]) if i == 0 else (g[1], g[2], g[0])
                a, b = int(a), int(b)
                paired.add(m.span(1 if i == 0 else 2))
                t = d["total"]
                if (a, b) != t or (p is not None and p != pct(*t)):
                    bad.append(f"{where}: stage K {a} of {b}" + (f" ({p}%)" if p else "")
                               + f"; generated {t[0]} of {t[1]} ({pct(*t)}%)")
        if not d["all_met"]:
            for m in EVERY.finditer(line):
                head = line[:m.end()]
                k = [x.end() for x in stage_marks.finditer(head)]
                h = [x.end() for x in H_MARK.finditer(head)]
                if k and (not h or k[-1] > h[-1]):
                    bad.append(f"{where}: says '{m.group(0)}' of stage K; an item is under the 60% per-item floor")
        # KF-3 rule for a figure after "share" that no item name stands next to.
        for m in SHARE.finditer(line):
            if m.span(2) in paired:
                continue
            win = line[:160] + " " + line[max(0, m.start() - 300):m.end() + 80]
            allowed = set()
            for s, it in d["suites"].items():
                if re.search(rf"\b{re.escape(s)}\b", win):
                    allowed.add(d["items"][it])
            for lm in LABEL.finditer(win):
                allowed.add(d["items"]["K-" + lm.group(1)])
            if rel in FILE_ITEM:
                allowed.add(d["items"][FILE_ITEM[rel]])
            if not allowed:
                continue
            allowed.add(d["total"])
            got = (int(m.group(2)), int(m.group(3)))
            if got not in allowed:
                bad.append(f"{where}: share {got[0]} of {got[1]}; allowed "
                           + ", ".join(f"{a} of {b}" for a, b in sorted(allowed)))
    return bad


def tracked(root):
    out = subprocess.run(["git", "ls-files", "*.md"], cwd=root, capture_output=True, text=True, check=True).stdout
    # Ruling registers record the figures of the day a ruling was made (dated history, like program/).
    return [p for p in out.split("\n") if p and not p.startswith("program/") and p not in PENDING
            and not re.match(r"specifications/stage-[a-z]+-rulings", p)
            and not p.startswith("oracle/OUTSIDE_SHARES")]


def self_test(root):
    d = load(root)
    a, b = d["items"]["K-8d"]
    ta, tb = d["items"]["F (existing traffic_light)"]
    sa, sb = d["total"]
    ok = lambda t, rel="x.md": not check_text(rel, t, d)  # noqa: E731
    caught = lambda t, rel="x.md": bool(check_text(rel, t, d))  # noqa: E731
    assert ok(f"Outside share {a} of {b} for `saccr_k`.")
    assert caught(f"Outside share {a} of {b - 3}; four leaked cases excluded (K-8d)."), "KF-3 shape"
    assert caught(f"Outside share: {a} of {b - 3} value cases", "specifications/06-risk/sa-ccr.md")
    assert ok("blind re-derivation 11 of 11 MATCH, `saccr_k`")
    assert ok(f"Stage K outside-check share: {sa} of {sb} value cases ({pct(sa, sb)}%).")
    assert ok(f"Outside share: `btk_k` 23 of 28 value cases and `tlk_k` {ta} of {tb}.")
    # The four lines the KF-18 audit planted, each of which the old gate passed.
    planted = ["Stage K outside-check share: 91 of 113 value cases (80.5%).",
               "Outside share: `btk_k` 23 of 28 value cases and `tlk_k` 11 of 11.",
               "Per item: K-4a 6 of 10, K-8d 12 of 16, `tlk_k` 11 of 11; every item meets 60%.",
               "Outside share 12 of 19 for `btk_k` and K-8d."]
    for t in planted:
        assert caught(t), f"planted line passed: {t}"
    # Each hole separately: the stage total with a wrong percentage, a later list member, a line without "share",
    # one item's figure beside another's name, a wrong per-item percentage, "every item meets" with an item under.
    assert caught(f"Stage K outside-check share: {sa} of {sb} value cases (80.5%).")
    assert caught(f"K 80.5% ({sa} of {sb} value cases)")
    assert caught(f"Outside share: K-8d {a} of {b}, K-4a 6 of 10, `tlk_k` {ta} of {tb + 1}.")
    assert caught(f"Outside-check rule per item: K-4a 6 of 10, `tlk_k` {ta} of {tb + 1}.")
    assert caught(f"Outside share: K-4a {a} of {b} and K-8d {a} of {b}.")
    assert caught(f"Outside share: K-8d {a} of {b} (99.0%).")
    if not d["all_met"]:
        assert caught(f"Stage K share {sa} of {sb}; every item at least 60%.")
        assert caught("Every stage K round 1 item meets the plan 15 per-item 60% rule.")
        assert ok("H 78.0% (stage H), every item at least 60%.")
    print("check_share_figures self-test: the KF-3 and KF-18 planted lines are caught, correct figures pass")


def main(argv):
    root = ROOT
    if "--root" in argv:
        root = Path(argv[argv.index("--root") + 1]).resolve()
    if "--self-test" in argv:
        self_test(root)
        return 0
    d = load(root)
    bad = []
    for rel in tracked(root):
        bad += check_text(rel, (root / rel).read_text(encoding="utf-8", errors="replace"), d)
    if bad:
        print("stage K share figures differ from oracle/OUTSIDE_SHARES.json:")
        print("\n".join("  " + b for b in bad))
        return 1
    print("stage K share figures agree with oracle/OUTSIDE_SHARES.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
