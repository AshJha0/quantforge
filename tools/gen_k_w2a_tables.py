#!/usr/bin/env python3
"""Generates the Java constants classes of the stage K wave 2 lane A shared tables (K-8a FRTB DRC and RRAO,
K-8f FRTB IMA).

The single source is specifications/tables/stage_k/mar22_drc.json, mar23_rrao.json, mar31_rfet.json,
mar32_pla.json and mar33_ima.json (ruling KR-50). Java has no build-time mechanism for reading them in this repo,
so this script writes one class per item and a check mode keeps the classes equal to the JSON, as
tools/gen_k_w1b_tables.py does for SA-CCR. Standard library only.

    python tools/gen_k_w2a_tables.py           write the Java files
    python tools/gen_k_w2a_tables.py --check   exit 1 if a generated file is stale
"""

import json
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "specifications" / "tables" / "stage_k"
OUT = ROOT / "java25" / "src" / "main" / "java" / "org" / "quantforge" / "risk"
HEADER = "// GENERATED by tools/gen_k_w2a_tables.py from specifications/tables/stage_k/{src}. Do not edit by hand.\n"

# Rating names of the operation (KR-51) and their keys in mar22_drc.json
RATINGS = ("AAA", "AA", "A", "BBB", "BB", "B", "CCC", "UNRATED", "DEFAULTED")
RATING_KEY = {"UNRATED": "Unrated", "DEFAULTED": "Defaulted"}


def entries(name):
    doc = json.loads((TABLES / f"{name}.json").read_text(encoding="utf-8"))
    return {e["key"]: e["value"] for e in doc["entries"]}


def num(v):
    """A Java double literal that parses to the same binary64 as the decimal string."""
    return repr(float(v))


def doubles(values):
    return "{" + ", ".join(num(v) for v in values) + "}"


def ints(values):
    return "{" + ", ".join(str(int(v)) for v in values) + "}"


def strings(values):
    return "{" + ", ".join(json.dumps(v) for v in values) + "}"


def percent(v):
    """A threshold such as "0.09" as the integer percentage 9 (KR-56 integer zone tests); exact or an error."""
    p = Decimal(v) * 100
    if p != p.to_integral_value():
        raise ValueError(f"{v} is not a whole percentage")
    return int(p)


def drc_class():
    t = entries("mar22_drc")
    r = entries("mar23_rrao")
    rw = [t["rw." + RATING_KEY.get(x, x)] for x in RATINGS]
    return (
        HEADER.format(src="mar22_drc.json and mar23_rrao.json")
        + f"""package org.quantforge.risk;

/** FRTB DRC and RRAO parameters (MAR22, MAR23), generated from mar22_drc.json and mar23_rrao.json (KR-50). */
final class FrtbDrcTables {{
    private FrtbDrcTables() {{}}

    /** MAR22.12: loss given default by seniority. */
    static final double LGD_COVERED = {num(t["lgd.covered_bond"])};
    static final double LGD_SENIOR = {num(t["lgd.senior_debt"])};
    static final double LGD_NON_SENIOR = {num(t["lgd.non_senior_debt"])};
    static final double LGD_EQUITY = {num(t["lgd.equity"])};
    /** MAR22.15, years. */
    static final double CAPITAL_HORIZON = {num(t["capital_horizon_years"])};
    /** MAR22.18. */
    static final double MATURITY_FLOOR = {num(t["maturity_weight_floor"])};
    /** MAR22.16: the short cash equity maturity choice. */
    static final double CASH_EQUITY_SHORT = {num(t["cash_equity_maturity_choices"][0])};
    /** MAR22.45. */
    static final double CTP_CROSS_FACTOR = {num(t["ctp_cross_index_factor"])};
    /** MAR22.24 Table 2: ratings in operation order and their default risk weights. */
    static final String[] RATINGS = {strings(RATINGS)};
    static final double[] RISK_WEIGHT = {doubles(rw)};
    /** MAR23.8(2). */
    static final double RRAO_EXOTIC = {num(r["rw.exotic_underlying"])};
    static final double RRAO_OTHER = {num(r["rw.other_residual_risk"])};
}}
"""
    )


def ima_class():
    f = entries("mar31_rfet")
    p = entries("mar32_pla")
    m = entries("mar33_ima")
    mult = p["backtest.zone_multiplier"]
    lows = {row: [lo for lo, _ in f["bucket." + row]] for row in "ABCD"}
    for row in "ABC":
        if f["bucket." + row][-1][1] != "inf":
            raise ValueError(f"row {row}: last bucket is not open")
    lh = m["lh.table"]
    return (
        HEADER.format(src="mar31_rfet.json, mar32_pla.json and mar33_ima.json")
        + f"""package org.quantforge.risk;

/** FRTB IMA parameters (MAR31, MAR32, MAR33), generated from mar31_rfet.json, mar32_pla.json, mar33_ima.json (KR-50). */
final class FrtbImaTables {{
    private FrtbImaTables() {{}}

    /** MAR31.13: RFET counts. */
    static final int RFET_MIN_DAYS = {int(f["rfet.min_obs_per_year"])};
    static final int RFET_WINDOW_DAYS = {int(f["rfet.window_days"])};
    static final int RFET_MIN_PER_WINDOW = {int(f["rfet.min_obs_per_window"])};
    static final int RFET_ALT_MIN_DAYS = {int(f["rfet.alt_min_obs_12m"])};
    static final int RFET_LOOKBACK_MONTHS = {int(f["rfet.lookback_months"])};
    /** MAR31.16 Table 1: bucket lower bounds per row; rows A to C end open, row D below RFET_D_UPPER. */
    static final double[] RFET_A = {doubles(lows["A"])};
    static final double[] RFET_B = {doubles(lows["B"])};
    static final double[] RFET_C = {doubles(lows["C"])};
    static final double[] RFET_D = {doubles(lows["D"])};
    static final double RFET_D_UPPER = {num(f["bucket.D"][-1][1])};
    /** MAR32.9 Table 1: multiplier by exceptions 0 to 9; 10 or more is MULTIPLIER_RED. */
    static final double[] MULTIPLIER = {doubles(mult[str(k)] for k in range(10))};
    static final double MULTIPLIER_RED = {num(mult["10+"])};
    /** MAR32.42 zone thresholds; the KS ones as whole percentages (KR-56). */
    static final double PLA_GREEN_SPEARMAN = {num(p["pla.green.spearman_above"])};
    static final double PLA_RED_SPEARMAN = {num(p["pla.red.spearman_below"])};
    static final long PLA_GREEN_KS_PERCENT = {percent(p["pla.green.ks_below"])};
    static final long PLA_RED_KS_PERCENT = {percent(p["pla.red.ks_above"])};
    /** MAR32.35. */
    static final int PLA_WINDOW = {int(p["pla.window_days"])};
    /** MAR33.3, MAR33.4. */
    static final double ES_CONFIDENCE = {num(m["es.confidence"])};
    static final int BASE_HORIZON = {int(m["es.base_horizon_days"])};
    /** MAR33.4 Table 1. */
    static final int[] LIQUIDITY_HORIZONS = {ints(m["lh.j"][str(j)] for j in range(1, 6))};
    /** MAR33.12 Table 2: categories and their liquidity horizons, in table order. */
    static final String[] LH_CATEGORY = {strings(lh.keys())};
    static final int[] LH_DAYS = {ints(lh.values())};
    /** MAR33.12 footnote 309. */
    static final String[] SPECIFIED_FX_PAIRS = {strings(m["lh.specified_fx_pairs"])};
    /** MAR33.15(2), MAR33.17(4). */
    static final double IMCC_RHO = {num(m["imcc.rho"])};
    static final double SES_RHO = {num(m["ses.rho"])};
}}
"""
    )


def outputs():
    return {OUT / "FrtbDrcTables.java": drc_class(), OUT / "FrtbImaTables.java": ima_class()}


def main(argv):
    check = "--check" in argv
    files = outputs()
    stale = []
    for path, text in files.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("stale (run python tools/gen_k_w2a_tables.py):", ", ".join(stale))
        return 1
    print(("checked " if check else "wrote ") + str(len(files)) + " files" + (f", updated {stale}" if stale and not check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
