"""Builds docs/question-bank/README.md from the question files. Run: python docs/question-bank/verify/build_index.py"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
LEVELS = ("foundation", "practitioner", "advanced")
Q = re.compile(r"^### (Q\d+\.\d+) (.+)$", re.M)
LV = re.compile(r"^\*Level: (foundation|practitioner|advanced)\.", re.M)


def main():
    rows, lists, total = [], {lv: [] for lv in LEVELS}, {lv: 0 for lv in LEVELS}
    for f in sorted(HERE.glob("[0-9][0-9]-*.md")):
        text = f.read_text(encoding="utf-8")
        title = re.search(r"^# Question bank \d+: (.+)$", text, re.M).group(1)
        qs, lvs = Q.findall(text), LV.findall(text)
        assert len(qs) == len(lvs), f"{f.name}: {len(qs)} questions, {len(lvs)} level lines"
        counts = {lv: lvs.count(lv) for lv in LEVELS}
        for lv in LEVELS:
            total[lv] += counts[lv]
        rows.append(f"| [{title}]({f.name}) | {counts['foundation']} | {counts['practitioner']} | {counts['advanced']} | {len(qs)} |")
        for (num, q), lv in zip(qs, lvs):
            lists[lv].append(f"- {num} ({f.name}) {q}")
    n = sum(total.values())
    out = [
        "# QuantForge question bank",
        "",
        f"A learning question bank and knowledge check: {n} questions with full answers, in {len(rows)} sets that follow the "
        "project's topics. It is for two readers. A newcomer can work through the foundation questions in order; a "
        "practitioner can jump to a set and test themselves against QuantForge's own conventions and rulings.",
        "",
        "How to use it: read the question, answer it on paper, then read the answer. Each answer starts with the plain "
        "idea, then gives the formal rule as the spec states it, then (for quantitative topics) a worked example with "
        "numbers, and ends with the pitfall that matters on a desk or in validation. Each question names its source "
        "spec or tutorial and an evidence class:",
        "",
        "- `computed`: the number was produced by running `quantforge_core`; a few are scratch formulas, and the answer says so.",
        "- `spec`: stated in a specification or ruling. `golden`: a named conformance golden case.",
        "- `literature`: a paper or book in the spec's sources. `design`: a project decision recorded in a ruling or ARCHITECTURE.",
        "",
        "Every worked-example number is rechecked by a script in `docs/question-bank/verify/` (one per set, `vNN_*.py`), "
        "which recomputes it and fails if the printed figure in the page differs. Run them from `python/` with "
        "`PYTHONPATH=.`. This page is generated by `verify/build_index.py`; do not edit it by hand.",
        "",
        "Levels: **foundation** (the idea and the convention), **practitioner** (using the library correctly and reading "
        "its outputs), **advanced** (edge cases, rulings, validation judgement).",
        "",
        "| Set | Foundation | Practitioner | Advanced | Questions |",
        "|---|---|---|---|---|",
        *rows,
        f"| **Total** | {total['foundation']} | {total['practitioner']} | {total['advanced']} | **{n}** |",
        "",
        "Back to [Learn QuantForge](../../LEARN.md).",
    ]
    for lv in LEVELS:
        out += ["", f"## {lv.capitalize()} questions", "", f"{total[lv]} questions.", "", *lists[lv]]
    (HERE / "README.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"index: {n} questions", total)


if __name__ == "__main__":
    main()
